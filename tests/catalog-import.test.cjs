'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const { execFileSync } = require('node:child_process');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');

test('shared country/alias catalogues reproduce the existing complete flag import without changing artwork', () => {
  const work = fs.mkdtempSync(path.join(os.tmpdir(), 'herald-flag-catalog-'));
  const manifest = (filename) =>
    JSON.parse(
      fs.readFileSync(filename, 'utf8').match(/window\.HVFlagAssets\s*=\s*(\{[\s\S]*\});/)[1],
    );
  // Historical manifest before rounded/TCC artwork was introduced, Git blob
  // 5a11d10095bb5415a6ad3b5ceab771b63baf8153 at commit b4ddc25ee897d04a6e1b439f223e32a13847ac81.
  // This expected output is not generated by the importer under test.
  const legacyManifest = require('./fixtures/slaps-flag-manifest.json');
  const currentManifest = fs.readFileSync(path.join(root, 'assets/flag-manifest.js'));
  const artworkDigest = () => {
    const hash = crypto.createHash('sha256');
    for (const file of new Set(Object.values(manifest(path.join(root, 'assets/flag-manifest.js'))))) {
      hash.update(file).update(fs.readFileSync(path.join(root, file)));
    }
    return hash.digest('hex');
  };
  const beforeArtwork = artworkDigest();
  try {
    fs.mkdirSync(path.join(work, 'data'));
    fs.mkdirSync(path.join(work, 'assets'));
    for (const file of ['country-catalog.json', 'flag-name-aliases.json']) {
      fs.copyFileSync(path.join(root, 'data', file), path.join(work, 'data', file));
    }
    for (const directory of ['flags', 'flags-extra']) {
      const source = path.join(root, 'assets', directory);
      const target = path.join(work, 'assets', directory);
      try {
        // Windows directory junctions do not need symbolic-link privileges.
        fs.symlinkSync(source, target, process.platform === 'win32' ? 'junction' : 'dir');
      } catch (error) {
        if (!['EPERM', 'EACCES', 'ENOTSUP'].includes(error.code)) throw error;
        // Restricted filesystems can still run the unchanged importer/assertions.
        fs.cpSync(source, target, {recursive: true});
      }
    }
    fs.copyFileSync(
      path.join(root, 'assets/slaps-countries.js'),
      path.join(work, 'assets/slaps-countries.js'),
    );
    const python = process.env.HV_PYTHON_PATH || process.env.PYTHON || (process.platform === 'win32' ? 'python' : 'python3');
    execFileSync(python, [path.join(root, 'scripts/import-slaps-flags.py')], {
      cwd: work,
      stdio: 'pipe',
    });
    assert.deepEqual(
      manifest(path.join(work, 'assets/flag-manifest.js')),
      legacyManifest,
    );
    const countries = require('../data/country-catalog.json');
    assert.equal(new Set(countries.map((country) => country.code)).size, countries.length);
    assert.equal(
      Object.keys(manifest(path.join(work, 'assets/flag-manifest.js'))).length,
      countries.length - 1,
    );
    assert.deepEqual(fs.readFileSync(path.join(root, 'assets/flag-manifest.js')), currentManifest, 'Legacy import leaves the current rounded/TCC manifest untouched');
    assert.equal(artworkDigest(), beforeArtwork, 'Legacy import never changes current artwork bytes');
  } finally {
    fs.rmSync(work, { recursive: true, force: true });
  }
});
